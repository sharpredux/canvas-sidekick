import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../../canvas-sidekick/package.json',import.meta.url));
const {_electron}=require('playwright');
const root=path.resolve(import.meta.dirname,'..');
const temporary=await fs.mkdtemp(path.join(os.tmpdir(),'sidekick-real-command-center-'));
const profile=path.join(temporary,'native');await fs.mkdir(profile);
const server=http.createServer((request,response)=>{response.writeHead(200,{'Content-Type':'application/json'});response.end(JSON.stringify(request.url.endsWith('/version')?{version:'test'}:request.url.endsWith('/tags')?{models:[{name:'qwen2.5:3b'}]}:[]));});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const origin=`http://127.0.0.1:${server.address().port}`;
await fs.writeFile(path.join(profile,'settings.json'),JSON.stringify({schoolUrl:origin,size:'Medium'}));
await fs.writeFile(path.join(profile,'state.json'),JSON.stringify({items:[{id:'host-fixture',type:'deadline',title:'Real host fixture',course:'Personal',dueDate:new Date(Date.now()+86400000).toISOString(),isManual:true,isCustom:true,timeEstimate:'30m'}]}));
const attributes=['service','canvas-sidekick-rust','profile',profile];
const session={origin,cookies:[{name:'canvas_session',value:'synthetic',domain:'127.0.0.1',path:'/',httpOnly:true}]};
assert.equal(spawnSync('secret-tool',['store','--label=Sidekick real host test',...attributes],{input:JSON.stringify(session)}).status,0);
let app;
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
async function eventually(predicate,label){for(let attempt=0;attempt<100;attempt++){if(await predicate())return;await wait(100);}throw new Error(label);}
try{
 app=await _electron.launch({executablePath:require('electron'),args:[path.join(root,'tools/command-center-gate.cjs')],env:{...process.env,COMMAND_CENTER_TEST_DATA:path.join(temporary,'host'),CANVAS_SIDEKICK_RUST:'1',CANVAS_SIDEKICK_PROFILE:profile,CANVAS_SIDEKICK_EXECUTABLE:path.join(root,'target/debug/canvas-sidekick'),CANVAS_SIDEKICK_OLLAMA_URL:origin+'/api',CANVAS_SIDEKICK_TEST_AUTOSTART_DIR:path.join(temporary,'autostart')}});
 const page=await app.firstWindow();await page.locator('[data-route="Tasks"]').waitFor();
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const parent=await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.getTitle()==='Command Center').getNativeWindowHandle().readUInt32LE(0));
 const child=()=>{const result=spawnSync('python3',[path.join(root,'tools/query-native-child.py'),String(parent)],{encoding:'utf8'});assert.equal(result.status,0,result.stderr);return JSON.parse(result.stdout);};
 await eventually(()=>Boolean(child()),'Native child not parented into the real Command Center');
 assert.equal(child().visible,false,'Native startup must be hidden on Dashboard');
 await page.locator('[data-route="Tasks"]').click();
 await page.locator('[data-task="canvas:host-fixture"]').waitFor();
 await page.locator('[data-task="canvas:host-fixture"]').check();
 await eventually(async()=>JSON.parse(await fs.readFile(path.join(profile,'state.json'),'utf8')).items.find(i=>i.id==='host-fixture').completed,'Host checkbox did not persist in the native app');
 await page.locator('[data-route="Canvas Sidekick"]').click();
 await eventually(()=>child().visible,'Native route did not show the child');
 const first=child();assert.equal(first.parent,parent);assert(first.width>500&&first.height>400);
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.getTitle()==='Command Center').setSize(1100,760));
 await eventually(()=>child().width<first.width,'Host resize did not reach the native child');
 const output=path.join(root,'artifacts/command-center');await fs.mkdir(output,{recursive:true});
 assert.equal(spawnSync('import',['-window',String(child().xid),path.join(output,'native.png')]).status,0);
 await page.locator('[data-route="Dashboard"]').click();
 await eventually(()=>!child().visible,'Leaving the native route did not hide the child');
 assert.deepEqual(errors,[]);
 await app.close();app=null;
 await eventually(()=>spawnSync('python3',['-c','import fcntl,sys; f=open(sys.argv[1],"r+"); fcntl.flock(f,fcntl.LOCK_EX|fcntl.LOCK_NB)',path.join(profile,'profile.lock')]).status===0,'Native child kept its profile locked after Command Center quit');
 console.log('PASS: actual Command Center navigation, native child, checkbox sync, resize, hide and shutdown; isolated profiles, no external providers.');
}finally{if(app)await app.close();spawnSync('secret-tool',['clear',...attributes]);await new Promise(resolve=>server.close(resolve));await fs.rm(temporary,{recursive:true,force:true});}
